import type { DamageCategory, ReportStatus, Severity } from '../types';
import { Badge } from './ui';

const STATUS_TONES: Record<ReportStatus, 'neutral' | 'info' | 'warning' | 'success' | 'danger' | 'violet' | 'accent'> = {
  submitted: 'neutral',
  under_review: 'info',
  verified: 'violet',
  assigned_for_repair: 'warning',
  in_progress: 'accent',
  resolved: 'success',
  rejected: 'danger',
};

export const STATUS_LABELS: Record<ReportStatus, string> = {
  submitted: 'Submitted',
  under_review: 'Under review',
  verified: 'Verified',
  assigned_for_repair: 'Assigned for repair',
  in_progress: 'In progress',
  resolved: 'Resolved',
  rejected: 'Rejected',
};

export const SEVERITY_LABELS: Record<Severity, string> = {
  low: 'Low',
  medium: 'Medium',
  high: 'High',
  critical: 'Critical',
};

export const CATEGORY_LABELS: Record<DamageCategory, string> = {
  pothole: 'Pothole',
  longitudinal_crack: 'Longitudinal crack',
  transverse_crack: 'Transverse crack',
  alligator_crack: 'Alligator crack',
  broken_surface: 'Broken surface',
  other: 'Other damage',
  unknown: 'Unclassified',
};

export function StatusBadge({ status }: { status: ReportStatus }) {
  return (
    <Badge tone={STATUS_TONES[status] ?? 'neutral'} dot>
      {STATUS_LABELS[status] ?? status.replace(/_/g, ' ')}
    </Badge>
  );
}

export function SeverityBadge({ severity }: { severity: Severity | null }) {
  if (!severity) return <Badge tone="neutral">Not rated</Badge>;
  const tone = severity === 'critical' ? 'danger' : severity === 'high' ? 'warning' : severity === 'medium' ? 'info' : 'success';
  return <Badge tone={tone}>{SEVERITY_LABELS[severity]}</Badge>;
}

export function CategoryBadge({ category }: { category: DamageCategory }) {
  return <Badge tone="neutral">{CATEGORY_LABELS[category] ?? category}</Badge>;
}

export function PriorityBadge({ score }: { score: number }) {
  const tone = score >= 75 ? 'danger' : score >= 55 ? 'warning' : score >= 35 ? 'info' : 'neutral';
  return (
    <Badge tone={tone} className="tabular-nums">
      {score.toFixed(0)}
    </Badge>
  );
}

export function DemoBadge({ show }: { show: boolean }) {
  if (!show) return null;
  return (
    <span
      className="inline-flex items-center gap-1 rounded-full border border-dashed border-amber-400 bg-amber-50 px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide text-amber-800 dark:border-amber-600 dark:bg-amber-950/70 dark:text-amber-200"
      title="Generated by the demo data generator — not a real citizen report"
    >
      Demo
    </span>
  );
}

export function ConfidenceMeter({ value }: { value: number | null }) {
  if (value === null || value === undefined) {
    return <span className="text-xs text-ink-400">—</span>;
  }
  const percent = Math.round(value * 100);
  return (
    <span className="inline-flex items-center gap-1.5" title="Model confidence — not a severity rating">
      <span className="h-1.5 w-10 overflow-hidden rounded-full bg-ink-200 dark:bg-ink-700">
        <span className="block h-full rounded-full bg-sky-500" style={{ width: `${percent}%` }} />
      </span>
      <span className="tabular-nums text-xs text-ink-600 dark:text-ink-300">{percent}%</span>
    </span>
  );
}
